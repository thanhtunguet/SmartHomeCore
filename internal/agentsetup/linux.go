package agentsetup

import (
	"fmt"
	"strings"
)

const (
	unitFileName  = "homecore-agent.service"
	rulesFileName = "50-homecore-agent.rules"
	// installedBinary is where the notes tell the user to put the binary; the unit's ExecStart uses it.
	installedBinary = "/usr/local/bin/homecore"
)

// polkitRules is deploy/polkit/50-homecore-agent.rules (a test keeps the two identical). It lets only
// the homecore-agent user power off or reboot through systemd-logind.
const polkitRules = "// /etc/polkit-1/rules.d/50-homecore-agent.rules  (polkit >= 0.106, JavaScript rules)\n" +
	"// Allows ONLY the homecore-agent user to power off / reboot via systemd-logind.\n" +
	"// The agent invokes `systemctl poweroff|reboot`; it never runs as root.\n" +
	"polkit.addRule(function (action, subject) {\n" +
	"    if (subject.user !== \"homecore-agent\") {\n" +
	"        return polkit.Result.NOT_HANDLED;\n" +
	"    }\n" +
	"    var allowed = [\n" +
	"        \"org.freedesktop.login1.power-off\",\n" +
	"        \"org.freedesktop.login1.power-off-multiple-sessions\",\n" +
	"        \"org.freedesktop.login1.reboot\",\n" +
	"        \"org.freedesktop.login1.reboot-multiple-sessions\"\n" +
	"    ];\n" +
	"    if (allowed.indexOf(action.id) >= 0) {\n" +
	"        return polkit.Result.YES;\n" +
	"    }\n" +
	"    return polkit.Result.NOT_HANDLED;\n" +
	"});\n"

// RenderUnit is the systemd unit for the Agent. The Agent identity and the trusted Controller key are
// arguments, so the service needs no config file and no writable directory (ProtectSystem=strict).
// It mirrors deploy/systemd/homecore-agent.service minus the config file and the state directory.
func RenderUnit(p Params) string {
	var b strings.Builder
	b.WriteString("# Generated by `homecore` from the command copied in the HomeCore web UI.\n")
	b.WriteString("# Install: /etc/systemd/system/homecore-agent.service. Runs unprivileged; power actions are\n")
	b.WriteString("# authorised by " + rulesFileName + " (polkit).\n")
	b.WriteString("[Unit]\nDescription=HomeCore Agent\nAfter=network-online.target\nWants=network-online.target\n\n")
	b.WriteString("[Service]\nType=simple\nUser=homecore-agent\nGroup=homecore-agent\n")
	b.WriteString("ExecStart=" + installedBinary + " " + strings.Join(p.Args(), " ") + "\n")
	b.WriteString("Restart=on-failure\nRestartSec=5s\n\n")
	b.WriteString(unitHardening)
	return b.String()
}

const unitHardening = `NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictNamespaces=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
# AF_UNIX is required to reach systemd-logind over D-Bus.
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX

[Install]
WantedBy=multi-user.target
`

// LinuxNotes are the installation steps printed after the files are written. exe is the binary that
// is running now; dir is where the files were written.
func LinuxNotes(p Params, exe, dir string) string {
	return fmt.Sprintf(`
Files written in %[1]s:
  %[2]s   systemd unit (Agent id and Controller key are in ExecStart)
  %[3]s   polkit rule that lets the homecore-agent user power off / reboot

Install them (run these lines on this machine; they need root):

  sudo useradd --system --no-create-home --shell /usr/sbin/nologin homecore-agent || true
  sudo install -m 0755 %[4]s %[5]s
  sudo install -m 0644 %[3]s /etc/polkit-1/rules.d/%[3]s
  sudo install -m 0644 %[2]s /etc/systemd/system/%[2]s
  sudo systemctl daemon-reload
  sudo systemctl enable --now homecore-agent

Check it:

  systemctl is-active homecore-agent
  curl -s http://127.0.0.1:%[6]d/agent/v1/healthz

Notes:
  - Allow TCP %[6]d from the Controller only (your LAN or VPN). Never forward it to the Internet.
  - polkit older than 0.106 (old Debian/Ubuntu) needs an equivalent .pkla file instead of the .rules file.
  - To change the id or the key later, run this setup again and install the new unit.
`, dir, unitFileName, rulesFileName, shQuote(exe), installedBinary, p.Port())
}

// shQuote quotes s for a POSIX shell.
func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }
