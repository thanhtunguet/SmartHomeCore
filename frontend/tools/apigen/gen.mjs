/**
 * Generates `src/api/generated/schema.d.ts` from the Controller's OpenAPI spec.
 *
 *   node tools/apigen/gen.mjs           write the file          (npm run gen:api)
 *   node tools/apigen/gen.mjs --check   fail if it is stale     (npm run check:api)
 *
 * Runs inside this workspace package so that openapi-typescript sees its own TypeScript 5 compiler
 * API; the UI itself is compiled with TypeScript 7, which has no such API.
 * The spec is `../api/openapi.yaml` of the SmartHomeCore repository (override with HOMECORE_SPEC).
 */
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, '../..');
const spec = process.env.HOMECORE_SPEC ? path.resolve(process.env.HOMECORE_SPEC) : path.resolve(frontend, '../api/openapi.yaml');
const target = path.join(frontend, 'src/api/generated/schema.d.ts');
const check = process.argv.includes('--check');

if (!existsSync(spec)) {
  console.error(`OpenAPI spec not found: ${spec}\nThe UI lives in the SmartHomeCore repository (frontend/); set HOMECORE_SPEC to use another path.`);
  process.exit(2);
}

const HEADER = `/**
 * GENERATED FILE, DO NOT EDIT.
 *
 * Wire types of the HomeCore Controller REST API, generated by openapi-typescript from
 * \`api/openapi.yaml\` of the SmartHomeCore repository:
 *
 *   npm run gen:api     regenerate
 *   npm run check:api   fail when this file is out of date with the spec
 *
 * Import through the friendly aliases in \`../schema.ts\`, not from here.
 * \`readOnly\`/\`writeOnly\` properties carry $Read/$Write markers: use Writable<T> for request
 * bodies and Readable<T> for responses (see \`../schema.ts\`).
 */
`;

const ast = await openapiTS(pathToFileURL(spec), {
  readWriteMarkers: true,
  // A `default` is a server-side behaviour, not a guarantee: keep defaulted properties optional so
  // request bodies need not repeat them (and old/partial responses stay representable).
  defaultNonNullable: false,
});
const output = HEADER + astToString(ast);

if (check) {
  // Regenerate to a temp file (never touching the committed one) and compare.
  const dir = mkdtempSync(path.join(tmpdir(), 'homecore-apigen-'));
  const tmp = path.join(dir, 'schema.d.ts');
  writeFileSync(tmp, output);
  const committed = existsSync(target) ? readFileSync(target, 'utf8') : null;
  const fresh = readFileSync(tmp, 'utf8');
  rmSync(dir, { recursive: true, force: true });
  if (committed !== fresh) {
    console.error(`${path.relative(frontend, target)} is ${committed === null ? 'missing' : 'out of date with ' + path.relative(frontend, spec)}.\nRun: npm run gen:api`);
    process.exit(1);
  }
  console.log(`${path.relative(frontend, target)} is up to date.`);
} else {
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, output);
  console.log(`wrote ${path.relative(frontend, target)} from ${spec}`);
}
